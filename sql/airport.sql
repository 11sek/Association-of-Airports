-- Проверка количества пассажиров на каждом рейсе
SELECT f.flight_id, f.departure_city, f.arrival_city,
       t.location AS arrival_city_terminal_location,
       t.terminal_name AS arrival_terminal,
       COUNT(tk.ticket_id) AS passenger_count
FROM flights f
JOIN terminals t ON t.terminal_id = f.terminal_id
LEFT JOIN tickets tk ON tk.flight_id = f.flight_id
GROUP BY f.flight_id
ORDER BY passenger_count DESC;
