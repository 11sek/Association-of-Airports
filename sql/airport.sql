
PRAGMA foreign_keys = ON;
DROP TABLE IF EXISTS baggage;
DROP TABLE IF EXISTS tickets;
DROP TABLE IF EXISTS flights;
DROP TABLE IF EXISTS terminals;
DROP TABLE IF EXISTS airplanes;
DROP TABLE IF EXISTS passengers;

CREATE TABLE passengers (
 passenger_id INTEGER PRIMARY KEY,
 first_name TEXT NOT NULL,
 last_name TEXT NOT NULL,
 passport_number TEXT NOT NULL UNIQUE,
 phone TEXT NOT NULL UNIQUE
);
CREATE TABLE airplanes (
 airplane_id INTEGER PRIMARY KEY,
 model TEXT NOT NULL,
 manufacturer TEXT NOT NULL,
 capacity INTEGER NOT NULL CHECK (capacity > 0)
);
CREATE TABLE terminals (
 terminal_id INTEGER PRIMARY KEY,
 terminal_name TEXT NOT NULL UNIQUE,
 location TEXT NOT NULL,
 number_of_gates INTEGER NOT NULL CHECK (number_of_gates > 0)
);
CREATE TABLE flights (
 flight_id INTEGER PRIMARY KEY,
 airplane_id INTEGER NOT NULL,
 terminal_id INTEGER NOT NULL,
 departure_city TEXT NOT NULL,
 arrival_city TEXT NOT NULL,
 departure_time DATETIME NOT NULL,
 arrival_time DATETIME NOT NULL,
 flight_status TEXT NOT NULL DEFAULT 'По расписанию',
 FOREIGN KEY (airplane_id) REFERENCES airplanes(airplane_id),
 FOREIGN KEY (terminal_id) REFERENCES terminals(terminal_id),
 CHECK (departure_city <> arrival_city)
);
CREATE TABLE tickets (
 ticket_id INTEGER PRIMARY KEY,
 passenger_id INTEGER NOT NULL,
 flight_id INTEGER NOT NULL,
 seat_number TEXT NOT NULL,
 ticket_price REAL NOT NULL CHECK (ticket_price > 0),
 FOREIGN KEY (passenger_id) REFERENCES passengers(passenger_id),
 FOREIGN KEY (flight_id) REFERENCES flights(flight_id),
 UNIQUE (flight_id, seat_number)
);
CREATE TABLE baggage (
 baggage_id INTEGER PRIMARY KEY,
 passenger_id INTEGER NOT NULL,
 ticket_id INTEGER NOT NULL,
 baggage_weight REAL NOT NULL CHECK (baggage_weight > 0 AND baggage_weight <= 100),
 baggage_type TEXT NOT NULL,
 FOREIGN KEY (passenger_id) REFERENCES passengers(passenger_id),
 FOREIGN KEY (ticket_id) REFERENCES tickets(ticket_id)
);
